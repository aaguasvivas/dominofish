// Golden traces (M1-04): plays seeded full games through Capi's engine and
// writes, per game, the deal of every round, every intent, the event, and
// the canonical state after every move (docs/FORMATS.md, Golden traces).
// Usage: node tools/capi-oracle/traces.mjs [out-dir]   (default fixtures/golden)
// Prints the rule-path counts per mode and writes them to coverage.txt.

import { mkdirSync, writeFileSync } from "node:fs";
import {
  PIN,
  loadCapi,
  mulberry32,
  tileIndex,
  tileText,
  canon,
  intentText,
  eventText,
  POLICIES,
  dealRecorder,
  checkDeal,
  pathsOf,
  openingPath,
} from "./lib.mjs";

const outDir = process.argv[2] ?? "fixtures/golden";
const GAMES = 150;
const WHOLE_SUIT_SEEDS = [59313, 83322, 282144, 645301];

// File name, mode, target, policy, and seeds of each trace set.
const SETS = [];
for (const [is2v2, base] of [[false, 100000], [true, 300000]]) {
  for (const target of [100, 200]) {
    const seeds = Array.from({ length: GAMES }, (_, i) => base + (target === 200 ? 100000 : 0) + i);
    SETS.push({ file: `${is2v2 ? "2v2" : "1v1"}-${target}.txt`, is2v2, target, policy: "raw", seeds });
  }
}
// The whole-suit seeds as mulberry32 deal seeds with Capi's fuzz policy and
// choice rng, as at invariants.fuzz.test.ts:357-360 and 467-469.
SETS.push({ file: "2v2-whole-suit.txt", is2v2: true, target: 100, policy: "capi-fuzz", seeds: WHOLE_SUIT_SEEDS });
SETS.push({ file: "2v2-whole-suit-200.txt", is2v2: true, target: 200, policy: "capi-fuzz", seeds: WHOLE_SUIT_SEEDS });

const capi = await loadCapi();
const counts = { "1v1": new Map(), "2v2": new Map() };
const bump = (mode, path) => counts[mode].set(path, (counts[mode].get(path) ?? 0) + 1);

function playGame({ is2v2, target, policy, seed }) {
  const mode = is2v2 ? "2v2" : "1v1";
  const lines = [`G ${mode} ${target} ${seed} ${policy}`];
  const deal = dealRecorder(mulberry32(seed));
  const choice = mulberry32(seed ^ 0x9e3779b9);
  const choose = POLICIES[policy];
  let state = capi.createInitialState({ mode: "live", theme: "colmado", is2v2, targetScore: target, rng: deal.rng });
  let order = deal.takeOrder();
  checkDeal(state, order, true);
  lines.push(`D ${order.map(tileIndex).join(",")}`);
  lines.push(`O ${state.starterThisRound} ${tileText(state.board[0])}`);
  lines.push(`S ${canon(state)}`);
  bump(mode, openingPath(state));
  for (let rounds = 0; ; rounds++) {
    if (rounds >= 200) throw new Error(`seed ${seed}: game did not end`);
    const round = { corridos: 0 };
    for (let steps = 0; state.phase === "playing"; steps++) {
      if (steps >= 400) throw new Error(`seed ${seed}: round did not end`);
      const seat = state.currentTurn;
      const intent = choose(capi, state, choice);
      const result = capi.applyMove(state, seat, intent);
      if (!result.success) throw new Error(`seed ${seed}: Capi rejected ${intentText(intent)}: ${result.error}`);
      for (const path of pathsOf(capi, state, seat, intent, result.newState, result, round)) bump(mode, path);
      state = result.newState;
      lines.push(`M ${seat} ${intentText(intent)} | ${eventText(state, result)} | ${canon(state)}`);
    }
    if (state.phase === "finished") break;
    state = capi.startNewRound(state, state.players, deal.rng);
    order = deal.takeOrder();
    checkDeal(state, order, false);
    lines.push(`D ${order.map(tileIndex).join(",")}`);
    lines.push(`S ${canon(state)}`);
  }
  lines.push("E");
  return lines;
}

mkdirSync(outDir, { recursive: true });
let games = 0;
let moves = 0;
let bytes = 0;
for (const set of SETS) {
  const header = [
    `# DominoFish golden traces from Capi's engine at ${PIN}.`,
    `# Generated by tools/capi-oracle/traces.mjs; never edit by hand. Format: docs/FORMATS.md.`,
    `# mode ${set.is2v2 ? "2v2" : "1v1"} target ${set.target} policy ${set.policy} games ${set.seeds.length}`,
  ];
  const body = [];
  for (const seed of set.seeds) {
    const lines = playGame({ ...set, seed });
    moves += lines.filter((l) => l.startsWith("M ")).length;
    body.push(...lines);
    games++;
  }
  const text = [...header, ...body].join("\n") + "\n";
  writeFileSync(`${outDir}/${set.file}`, text);
  bytes += Buffer.byteLength(text);
}

const coverage = [`# Rule-path counts of the golden traces at ${PIN}; generated by tools/capi-oracle/traces.mjs.`];
for (const mode of ["1v1", "2v2"]) {
  for (const [path, n] of [...counts[mode]].sort()) coverage.push(`${mode} ${path} ${n}`);
}
writeFileSync(`${outDir}/coverage.txt`, coverage.join("\n") + "\n");
console.log(coverage.slice(1).join("\n"));
console.log(`traces: ${games} games, ${moves} moves, ${bytes} bytes in ${SETS.length} files`);
